# ------------------------------------------------- the law's exponent, fitted
def power_fit(pairs):
    """log(ratio - 1) = log c - alpha log n; returns alpha, its s.e., R^2."""
    x = np.log([n for n, _ in pairs])
    y = np.log([r - 1 for _, r in pairs])
    A = np.vstack([x, np.ones_like(x)]).T
    coef, *_ = np.linalg.lstsq(A, y, rcond=None)
    pred = A @ coef
    r2 = 1 - ((y - pred) ** 2).sum() / ((y - y.mean()) ** 2).sum()
    se = np.sqrt(((y - pred) ** 2).sum() / (len(x) - 2)
                 / ((x - x.mean()) ** 2).sum())
    return -coef[0], se, r2


