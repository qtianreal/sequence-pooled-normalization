def add(name, value):
    if name in MACROS:
        raise SystemExit(f"duplicate macro: {name}")
    MACROS[name] = value


def load(name):
    return json.loads((RESULTS / name).read_text())


def sd(v):
    return np.std(v, ddof=1) if len(v) > 1 else 0.0


# The paper says "all measurements use N seeds", so N has to come from the
# results rather than from a typed word: adding seeds to one experiment and
# not the others must break the build, not quietly leave the claim standing.
WORDS = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six",
         7: "seven", 8: "eight", 9: "nine", 10: "ten"}


def _seed_count():
    counts = {f: len({r["seed"] for r in load(f) if "seed" in r})
              for f in TRAINED}
    distinct = set(counts.values())
    if len(distinct) != 1:
        raise SystemExit(
            "the paper claims one seed count for all measurements, but the "
            "results disagree; say so per experiment instead:\n  "
            + "\n  ".join(f"{f}: {n}" for f, n in sorted(counts.items())))
    n = distinct.pop()
    return WORDS.get(n, str(n))


def reach_worth(rows, norm, lo, hi, key="retrained"):
    """Per-seed difference between the largest and smallest reach."""
    seeds = sorted({r["seed"] for r in rows})
    out = []
    for s in seeds:
        a = [r[key] for r in rows if r["norm"] == norm and r["seed"] == s
             and r["prefix"] == lo]
        b = [r[key] for r in rows if r["norm"] == norm and r["seed"] == s
             and r["prefix"] == hi]
        if a and b:
            out.append(b[0] - a[0])
    return np.array(out)


