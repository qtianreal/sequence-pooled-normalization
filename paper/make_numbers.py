def _un_worth(rows, norm):
    """Reach worth, paired on seed: deepest minus shallowest."""
    out = []
    for sd_ in sorted({r["seed"] for r in rows}):
        a = [r["retrained"] for r in rows
             if r["norm"] == norm and r["seed"] == sd_ and r["depth"] == un_lo]
        b = [r["retrained"] for r in rows
             if r["norm"] == norm and r["seed"] == sd_ and r["depth"] == un_hi]
        if a and b:
            out.append(b[0] - a[0])
    return np.array(out)


